// Keep browser prompts identical to the server's source markdown.
import { readFileSync, writeFileSync } from "node:fs";

const files = { V2: "prompt_v2.md", ADDENDUM: "task1_addendum_v2.md", REPORT: "prompt_report_v1.md", REWRITE: "band9_rewrite.md" };
const text = Object.entries(files).map(([name, file]) =>
  `export const ${name} = ${JSON.stringify(readFileSync(new URL(`../server/prompts/${file}`, import.meta.url), "utf8"))};`
).join("\n");
const output = new URL("../shared/prompts.generated.js", import.meta.url);
const generated = "// Generated by scripts/generate-prompts.js; edit server/prompts/*.md instead.\n" + text + "\n";
let current = "";
try { current = readFileSync(output, "utf8"); } catch { /* first generation */ }
if (current !== generated) writeFileSync(output, generated);
